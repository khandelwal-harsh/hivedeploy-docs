test('ArrowUp on the first option wraps to the last, and ArrowDown wraps back', async ({ page }) => {
  test.skip(page.viewportSize()!.width < 768)
  await page.goto('/quickstart')
  await page.waitForLoadState('networkidle')
  await page.keyboard.press('ControlOrMeta+k')
  await page.keyboard.type('external ID')
  const dlg = page.getByTestId('search-palette')
  const box = dlg.getByRole('combobox')
  await expect(dlg.getByRole('option').first()).toBeVisible()
  const ids = await dlg.getByRole('option').evaluateAll((os) => os.map((o) => o.id))
  expect(ids.length).toBeGreaterThan(1)
  await expect(box).toHaveAttribute('aria-activedescendant', ids[0]!)
  await page.keyboard.press('ArrowUp')
  await expect(box).toHaveAttribute('aria-activedescendant', ids[ids.length - 1]!)
  await expect(dlg.locator(`[id="${ids[ids.length - 1]}"]`)).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('ArrowDown')
  await expect(box).toHaveAttribute('aria-activedescendant', ids[0]!)
})
